// Optional browser check: NODE_PATH=/path/to/node_modules node tests/browser.cjs
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const {mkdtempSync,rmSync}=require('node:fs');
const {tmpdir}=require('node:os');
const path=require('node:path');
const temp=mkdtempSync(path.join(tmpdir(),'fieldwork-test-'));
const port=process.env.TEST_PORT||'8765';
const server=spawn('python',['app.py'],{cwd:path.join(__dirname,'..'),env:{...process.env,PORT:port,RESEARCH_DB:path.join(temp,'research.db'),OPENAI_API_KEY:''},stdio:['ignore','pipe','inherit']});
let browser;
const cleanup=()=>{server.kill();rmSync(temp,{recursive:true,force:true})};
(async()=>{
 await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(Error('Test server exited: '+code)))});
 browser=await chromium.launch({...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${port}/`);
 await page.getByRole('heading',{name:'Big questions. Clearer answers.'}).waitFor();
 await page.screenshot({path:'/tmp/fieldwork-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Explore sample',exact:true}).click();
 await page.getByRole('heading',{name:'A closer look at the evidence'}).waitFor();
 await page.getByRole('tab',{name:'Evidence table'}).click();
 if(await page.locator('tbody tr').count()<3)throw Error('Missing evidence rows');
 await page.getByRole('tab',{name:/Sources/}).click();
 if(await page.locator('.source-card').count()!==3)throw Error('Missing sources');
 await page.getByRole('tab',{name:'Research brief'}).click();
 await page.locator('.citation').first().click();
 await page.getByRole('heading',{name:'The sources behind the story'}).waitFor();
 await page.screenshot({path:'/tmp/fieldwork-report.png',fullPage:true});
 await page.goto(`http://127.0.0.1:${port}/#overview`);
 await page.getByRole('button',{name:'New research',exact:true}).click();
 await page.locator('[name=question]').fill('How can researchers verify the claims in generated reports?');
 await page.locator('[name=discovery]').selectOption('no');
 await page.locator('#source-details summary').click();
 await page.locator('[name=sourceTitle]').fill('Research methods note');
 await page.locator('[name=sourceText]').fill('Researchers should trace each claim to a specific passage in an original source. Matching a quotation to source text establishes provenance but does not prove the truth of a claim.');
 await page.getByRole('button',{name:'Begin research',exact:false}).click();
 await page.getByRole('heading',{name:'A closer look at the evidence'}).waitFor({timeout:15000});
 if(!(await page.locator('.report-meta').innerText()).includes('Extractive brief'))throw Error('Missing fallback label');
 const download=page.waitForEvent('download');
 await page.getByRole('link',{name:'Export report'}).click();
 const d=await download; await d.saveAs('/tmp/fieldwork-export.md');
 await page.reload();await page.getByRole('heading',{name:'A closer look at the evidence'}).waitFor();
 await page.goto(`http://127.0.0.1:${port}/#library`);
 await page.getByRole('heading',{name:'A library of perspectives.'}).waitFor();
 await page.getByRole('textbox',{name:'Search library'}).fill('Research methods note');
 if(await page.locator('.library-row').count()!==1)throw Error('Source filter failed');
 await page.setViewportSize({width:390,height:844});
 await page.goto(`http://127.0.0.1:${port}/#overview`);
 await page.getByRole('heading',{name:'Big questions. Clearer answers.'}).waitFor();
 await page.screenshot({path:'/tmp/fieldwork-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.getByRole('button',{name:'New research',exact:true}).click();
 await page.locator('[name=question]').fill('Does research need source verification?');
 await page.locator('[name=discovery]').selectOption('no');
 await page.getByRole('button',{name:'Begin research',exact:false}).click();
 await page.getByRole('alert').filter({hasText:'Add a URL'}).waitFor();
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: desktop/mobile rendering, sample, evidence, citation navigation, real excerpt workflow, export, persistence, library search, validation; no browser errors.');
 await browser.close(); cleanup();
})().catch(async e=>{console.error(e);if(browser)await browser.close();cleanup();process.exit(1)});
